-- Oracle Database 19c+ : table de staging pour mouvements de stock
-- Importer data/stock_nettoye.csv via SQL Developer (assistant Import Data).
-- Conserver LIGNE_SOURCE comme clé unique technique : ID_MOUVEMENT est parfois répété.
CREATE TABLE RETAILAI_MOUVEMENTS_STOCK (
    ID_MOUVEMENT VARCHAR2(40),
    DATE_MOUVEMENT DATE,
    TYPE_MOUVEMENT VARCHAR2(30),
    CODE_PRODUIT VARCHAR2(30),
    PRODUIT VARCHAR2(250),
    CATEGORIE VARCHAR2(100),
    UNITE VARCHAR2(40),
    PRIX_ACHAT_UNITAIRE NUMBER(14,2),
    QUANTITE NUMBER(14,2),
    STOCK_SECURITE NUMBER(14,2),
    STOCK_MAXIMUM NUMBER(14,2),
    NUMERO_LOT VARCHAR2(60),
    DATE_EXPIRATION DATE,
    CODE_ENTREPOT VARCHAR2(30),
    ENTREPOT VARCHAR2(150),
    VILLE VARCHAR2(100),
    REGION VARCHAR2(150),
    TIERS VARCHAR2(150),
    DELAI_LIVRAISON_JOURS NUMBER(10),
    LIGNE_SOURCE NUMBER(10) PRIMARY KEY
);

-- SQL Developer : lors de l'import, définir le format des dates YYYY-MM-DD.
-- Vue : variations de stock calculables, pas stock disponible réel.
CREATE OR REPLACE VIEW RETAILAI_VARIATION_STOCK AS
SELECT CODE_PRODUIT, PRODUIT, CODE_ENTREPOT, ENTREPOT,
       SUM(CASE WHEN TYPE_MOUVEMENT = 'ENTREE' THEN QUANTITE
                WHEN TYPE_MOUVEMENT = 'SORTIE' THEN -QUANTITE
                ELSE 0 END) AS VARIATION_NETTE,
       COUNT(*) AS NB_MOUVEMENTS,
       SUM(CASE WHEN QUANTITE IS NULL THEN 1 ELSE 0 END) AS NB_QUANTITES_MANQUANTES
FROM RETAILAI_MOUVEMENTS_STOCK
GROUP BY CODE_PRODUIT, PRODUIT, CODE_ENTREPOT, ENTREPOT;

-- Vérifications après import
SELECT COUNT(*) AS NB_LIGNES FROM RETAILAI_MOUVEMENTS_STOCK;
SELECT ID_MOUVEMENT, COUNT(*) AS OCCURRENCES
FROM RETAILAI_MOUVEMENTS_STOCK
GROUP BY ID_MOUVEMENT HAVING COUNT(*) > 1;
SELECT * FROM RETAILAI_VARIATION_STOCK ORDER BY CODE_PRODUIT, CODE_ENTREPOT;
